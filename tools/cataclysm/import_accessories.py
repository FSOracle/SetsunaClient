"""Port the original Cataclysm Curios layer definitions and textures without OBJ conversion."""
import argparse
import pathlib
import re
import zipfile


MODELS = {
    "BELT_OF_BEGINNER": ("Belt_Of_Beginner_Model", "0.2F"),
    "BELT_OF_MONSTROSITY": ("Belt_Of_Monstrosity_Model", "0.2F"),
    "BERSERKER_SOUL_AMULET": ("Berserker_Soul_Amulet_Model", "0.2F"),
    "BLAZING_GRIPS": ("Blazing_Grips_Model", "0.0F"),
    "CHITIN_CLAW": ("Chitin_Claw_Model", "0.0F"),
    "SANDSTORM_IN_A_BOTTLE": ("Sandstorm_In_A_BottleModel", "0.2F"),
    "STICKY_GLOVES": ("Sticky_Gloves_Model", "0.2F"),
    "STURDY_BOOTS": ("Sturdy_Boots_Model", "0.3F"),
    "UNBREAKABLE_SKULL": ("Unbreakable_Skull_Model", "0.2F"),
    "VITALITY_ANKH": ("Vitality_Ankh_Model", "0.2F"),
}
METHODS = {
    "m_170681_": "createMesh", "m_171576_": "getRoot", "m_171597_": "getChild",
    "m_171599_": "addOrReplaceChild", "m_171558_": "create", "m_171514_": "texOffs",
    "m_171488_": "addBox", "m_171419_": "offset", "m_171423_": "offsetAndRotation",
    "m_171565_": "create", "m_171480_": "mirror", "m_171555_": "mirror",
    "m_171469_": "extend",
}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=pathlib.Path, required=True,
                        help="CFR source root containing com/github/L_Ender/cataclysm")
    parser.add_argument("--jar", type=pathlib.Path, required=True)
    parser.add_argument("--project", type=pathlib.Path, default=pathlib.Path(__file__).resolve().parents[2])
    args = parser.parse_args()
    imports = """package com.setsuna.cosmetic;

import net.minecraft.client.model.HumanoidModel;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeDeformation;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;

/** Original Cataclysm 3.31 layer geometry; generated by tools/cataclysm/import_accessories.py. */
final class CataclysmAccessoryModels {
    private CataclysmAccessoryModels() { }

    static ModelPart bake(CataclysmAccessory accessory, boolean slim) {
        return switch (accessory) {
"""
    methods = []
    for key, (name, deformation) in MODELS.items():
        source = args.source / "com/github/L_Ender/cataclysm/client/model/item/CuriosModel" / (name + ".java")
        text = source.read_text(encoding="utf-8")
        match = re.search(r"public static LayerDefinition (?:createLayer|createBodyLayer)\(([^)]*)\) \{(.*?)\n    }", text, re.S)
        if not match:
            raise ValueError(f"No layer definition in {source}")
        signature, body = match.groups()
        method = key.lower()
        for old, new in METHODS.items():
            body = body.replace(old, new)
        if re.search(r"m_\d+_", body):
            raise ValueError(f"Unmapped method in {name}")
        # Each custom subtree uses the atlas area outside the transparent vanilla skin UVs.
        methods.append(f"    private static LayerDefinition {method}({signature}) {{{body}\n    }}\n")
        arguments = "slim, " if "boolean slim" in signature else ""
        imports += f"            case {key} -> {method}({arguments}new CubeDeformation({deformation})).bakeRoot();\n"
    output = imports + "        };\n    }\n\n" + "\n".join(methods) + "}\n"
    target = args.project / "src/main/java/com/setsuna/cosmetic/CataclysmAccessoryModels.java"
    target.write_text(output, encoding="utf-8", newline="\n")
    textures = args.project / "src/main/resources/assets/setsuna/textures/cosmetics/cataclysm"
    textures.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(args.jar) as jar:
        names = [key.lower() for key in MODELS]
        names[names.index("unbreakable_skull")] = "unbreakable_skull2"
        names += ["blazing_grips_layer", "berserker_soul_amulet_layer"]
        for name in names:
            (textures / (name + ".png")).write_bytes(jar.read("assets/cataclysm/textures/curiositem/" + name + ".png"))
    print(f"Imported {len(MODELS)} model definitions and {len(names)} original textures")


if __name__ == "__main__":
    main()
