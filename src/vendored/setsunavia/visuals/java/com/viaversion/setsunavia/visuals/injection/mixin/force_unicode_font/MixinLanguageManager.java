package com.viaversion.setsunavia.visuals.injection.mixin.force_unicode_font;

import com.viaversion.setsunavia.SetsunaVia;
import com.viaversion.setsunavia.visuals.features.force_unicode_font.UnicodeFontFix1_12_2;
import net.minecraft.client.resources.language.LanguageManager;
import net.minecraft.server.packs.resources.ResourceManager;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(LanguageManager.class)
public abstract class MixinLanguageManager {

    @Inject(method = "onResourceManagerReload", at = @At("RETURN"))
    private void updateUnicodeFontOverride(ResourceManager manager, CallbackInfo ci) {
        UnicodeFontFix1_12_2.updateUnicodeFontOverride(SetsunaVia.getImpl().getTargetVersion());
    }

}
